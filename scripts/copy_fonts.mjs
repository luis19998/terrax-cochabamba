// Copies Plus Jakarta Sans (npm package @fontsource/plus-jakarta-sans) into the static site, which does not serve
// node_modules:   npm install   then   node scripts/copy_fonts.mjs
// Only the "latin" subset is copied: it already includes á é í ó ú ñ ü and the apostrophe used in Quechua.
import { copyFileSync, mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const from = join(root, "node_modules/@fontsource/plus-jakarta-sans/files");
const to = join(root, "web/vendor/fonts/plus-jakarta-sans");
mkdirSync(to, { recursive: true });
const range = "U+0000-00FF,U+0131,U+0152-0153,U+02BB-02BC,U+02C6,U+02DA,U+02DC,U+0304,U+0308,U+0329,U+2000-206F,U+20AC,U+2122,U+2191,U+2193,U+2212,U+2215,U+FEFF,U+FFFD";
let css = "/* Plus Jakarta Sans (SIL Open Font License 1.1), from @fontsource/plus-jakarta-sans. Generated by scripts/copy_fonts.mjs */\n";
for (const weight of [400, 500, 600, 700, 800]) {
  const file = `plus-jakarta-sans-latin-${weight}-normal.woff2`;
  copyFileSync(join(from, file), join(to, file));
  css += `@font-face { font-family: "Plus Jakarta Sans"; font-style: normal; font-display: swap; font-weight: ${weight}; src: url("./${file}") format("woff2"); unicode-range: ${range}; }\n`;
}
writeFileSync(join(to, "fonts.css"), css);
console.log("Fuente copiada a web/vendor/fonts/plus-jakarta-sans/");
